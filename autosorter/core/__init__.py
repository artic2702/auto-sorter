# This empty file makes "core" a Python package.
#
# WHY THIS FILE EXISTS:
# In Python, a folder is just a folder. But if you put an __init__.py inside it,
# Python treats it as a "package" — meaning you can import from it:
#
#   from autosorter.core.db import Database   ← this only works because __init__.py exists
#
# Without __init__.py, Python would say: "ModuleNotFoundError: No module named 'autosorter.core'"
